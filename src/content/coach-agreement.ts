/**
 * Соглашение тренера о конфиденциальности данных клиентов. Тренер заполняет реквизиты в кабинете,
 * текст собирается с его данными и подписывается простой электронной подписью (код из письма).
 * Новая редакция — поднять версию: тренеры подпишут заново при следующем входе.
 * Перед запуском текст стоит показать юристу.
 *
 * Разметка: «## » — подзаголовок, «- » — пункт списка, пустая строка — новый абзац.
 */
import { SELLER, SITE } from "@/lib/site";

export const COACH_AGREEMENT_VERSION = "2026-10-30";
export const COACH_AGREEMENT_TITLE = "Соглашение о конфиденциальности данных клиентов";

export const TAX_STATUS: Record<string, string> = { SELF: "самозанятый (плательщик НПД)", IP: "индивидуальный предприниматель", PERSON: "физическое лицо" };

const domain = SITE.url.replace(/^https?:\/\//, "");

export function coachAgreementBody(p: { fullName: string; taxStatus: string; inn: string | null; phone: string; email: string; date: string }) {
  const who = `${p.fullName}, ${TAX_STATUS[p.taxStatus] ?? "физическое лицо"}${p.inn ? `, ИНН ${p.inn}` : ""}, телефон ${p.phone}, адрес электронной почты ${p.email}`;
  return `г. Краснодар, ${p.date}

${SELLER.name} (ИНН ${SELLER.inn}, ОГРНИП ${SELLER.ogrnip}, адрес: ${SELLER.legalAddress}), далее — Оператор, и ${who}, далее — Тренер, вместе — Стороны, заключили настоящее соглашение (далее — Соглашение).

## 1. Предмет
1.1. Оператор предоставляет Тренеру доступ к личному кабинету тренера на сайте ${domain} (далее — Кабинет). В Кабинете Тренер видит заявки и записи клиентов на свои тренировки.

1.2. Вместе с записью Тренер получает персональные данные клиента (далее — Данные):
- фамилию, имя, отчество — в том виде, как они указаны в аккаунте;
- номер телефона или адрес электронной почты;
- комментарий к записи;
- дату, время и клуб тренировки, отметки о посещении.

1.3. Данные передаются Тренеру на основании согласия клиента, которое он даёт при записи («Согласие на передачу данных тренеру», ${domain}/p/coach-consent). Данные клиентов, которых Тренер сам вносит в дневник Кабинета, он вносит только с согласия этих клиентов.

## 2. Обязанности Тренера
2.1. Использовать Данные только чтобы:
- связаться с клиентом по записи: подтвердить, перенести или отменить тренировку, уточнить уровень подготовки;
- провести тренировку и вести дневник тренировок в Кабинете.

2.2. Не передавать Данные третьим лицам и не раскрывать их, в том числе:
- не пересылать их другим тренерам, клубам и знакомым;
- не добавлять клиентов в общие чаты и группы без их просьбы;
- не публиковать имена и телефоны клиентов в социальных сетях.

2.3. Не использовать Данные для рекламы и рассылок — своих или чужих.

2.4. Обеспечивать безопасность Данных:
- не сообщать никому пароль от Кабинета и не входить в него с чужих устройств;
- защитить телефон и компьютер, на которых хранятся контакты клиентов, паролем или биометрией;
- не выгружать списки клиентов в таблицы и не хранить их в иностранных облачных сервисах.

2.5. В течение 24 часов сообщать Оператору на ${SELLER.email}, если Данные могли попасть к посторонним: потерян телефон, взломан аккаунт, клиентам пишут незнакомцы.

## 3. Удаление данных и срок действия
3.1. По требованию Оператора (например, если клиент отозвал согласие) Тренер удаляет Данные клиента из телефона, мессенджеров и заметок и подтверждает это письмом не позднее 10 дней с даты требования.

3.2. При прекращении работы через сайт доступ к Кабинету закрывается. Тренер удаляет Данные клиентов, полученные через сайт, в течение 10 дней — кроме контактов клиентов, которые сами дали их Тренеру лично.

3.3. Соглашение действует с даты подписания бессрочно. Обязанность хранить конфиденциальность Данных сохраняется 3 года после прекращения работы через сайт.

## 4. Ответственность
4.1. За нарушение раздела 2 Оператор вправе сразу закрыть Тренеру доступ к Кабинету и снять его страницу с сайта.

4.2. Тренер возмещает Оператору убытки, в том числе штрафы, наложенные на Оператора, если они возникли из-за нарушения Тренером Соглашения.

4.3. Споры разрешаются переговорами, а если не договорились — в суде по месту нахождения Оператора.

## 5. Подписание
5.1. Тренер подписывает Соглашение в Кабинете: проверяет свои данные, отмечает согласие с текстом и вводит код, который Оператор отправляет на адрес электронной почты Тренера, указанный выше.

5.2. Стороны признают такое подписание простой электронной подписью Тренера (ст. 6 и 9 Федерального закона от 06.04.2011 № 63-ФЗ «Об электронной подписи»), а Соглашение — равнозначным документу на бумаге, подписанному собственноручно. Тренер обязуется не передавать доступ к своей почте и Кабинету третьим лицам.

5.3. Соглашение со стороны Оператора считается подписанным с момента его подписания Тренером: Оператор предлагает его на этих условиях всем тренерам, которым выдан доступ к Кабинету. Подписанный текст хранится у Оператора и доступен Тренеру в Кабинете.`;
}
