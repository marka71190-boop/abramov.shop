const PATRONYMIC = /(ович|евич|ьич|ична|инична|овна|евна)$/i;
// Типичные окончания фамилий
const SURNAME = /(ов|ев|ёв|ин|ын|ский|цкий|ской|цкой|ская|цкая|ова|ева|ёва|ина|ына|енко|ук|юк|чук|ян|янц|дзе|швили|ых|их|ман|берг|штейн)$/i;

const norm = (w: string) => w.toLowerCase().replace(/ё/g, "е");
const cap = (w: string) => (w ? w.charAt(0).toLocaleUpperCase("ru-RU") + w.slice(1) : w);
const isName = (w: string) => NAMES.has(norm(w));

/** Имя и отчество из полного имени; фамилия — отброшена */
export function parseName(full: string | null | undefined): { first: string; patronymic: string } {
  const words = String(full ?? "")
    .replace(/[^\p{L}\s'-]/gu, " ")
    .trim()
    .split(/\s+/)
    .filter((w) => w.length > 1);
  if (!words.length) return { first: "", patronymic: "" };
  // Название организации вместо имени — обращаемся без имени
  if (words.some((w) => /^(ооо|ип|ао|зао|пао|оао|тоо|llc|ltd)$/i.test(w))) return { first: "", patronymic: "" };

  // «Иванов Иван Иванович» / «Иван Иванович Иванов» / «Иван Иванович»
  const p = words.findIndex((w, i) => i > 0 && PATRONYMIC.test(w) && w.length > 5 && !isName(w));
  if (p > 0 && words.length >= 2) {
    const first = words[p - 1];
    // «Марк Абрамович»: если отчество — последнее из двух слов, а первое имя — это имя и отчество.
    if (isName(first) || words.length >= 3 || !SURNAME.test(first)) return { first: cap(first), patronymic: cap(words[p]) };
  }

  const known = words.find(isName);
  if (known) return { first: cap(known), patronymic: "" };

  const notSurname = words.filter((w) => !SURNAME.test(w) && !PATRONYMIC.test(w));
  if (words.length === 1) return { first: notSurname.length ? cap(words[0]) : "", patronymic: "" };
  // «Абрамов Марк»: фамилию узнали по окончанию — берём другое слово
  if (notSurname.length) return { first: cap(notSurname[0]), patronymic: "" };
  return { first: "", patronymic: "" };
}

/** Только имя — для писем и уведомлений («Здравствуйте, Марк!»). Пусто, если не поняли */
export const firstNameOf = (full: string | null | undefined) => parseName(full).first;

/** Имя для писем, с учётом того, что человек указал сам */
export const callNameOf = (u: { name: string | null; callName?: string | null }) => u.callName?.trim() || parseName(u.name).first;

/**
 * Обращение в кабинете: имя, которое человек указал сам в «Как к вам обращаться», иначе —
 * понятое из полного имени; плюс отчество, если оно указано отдельно или есть в полном имени.
 */
export function greetingOf(u: { name: string; callName?: string | null; patronymic?: string | null }) {
  const parsed = parseName(u.name);
  const first = u.callName?.trim() || parsed.first;
  if (!first) return "";
  const patronymic = u.callName?.trim() ? "" : parsed.patronymic;
  const pat = u.patronymic?.trim() || patronymic;
  return pat ? `${first} ${pat}` : first;
}
