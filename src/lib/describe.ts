export interface DescribeInput {
  /** Наше название товара */
  name: string;
  group: Group;
  /** Характеристики поставщика как есть */
  specs: Spec[];
  /** Имена характеристик, которые уже попали в наши характеристики карточки — в списке внизу их не повторяем */
  shown?: string[];
}

/** Описание товара обычным текстом (абзацы через пустую строку) */
export function describe(input: DescribeInput) {
  const seed = seedOf(input.name);
  let turn = 0;
  const pick = <T,>(list: T[]) => list[(seed + turn++ * 7) % list.length];
  const ctx: Ctx = { group: input.group, pick };
  const get = (re: RegExp) => input.specs.find((s) => re.test(s.name))?.value ?? null;
  const name = noDot(input.name.trim());

  // 1. Вступление: что это и чьё
  const brand = get(/^бренд$/i)?.replace(/\s*\([^)]*\)/g, "").trim() ?? null;
  const country = get(/^страна производства$/i);
  const place = country ? (/^кнр$/i.test(country) ? "Китай" : country) : null;
  const made = brand && place ? pick([`Бренд — ${brand}, производство — ${place}.`, `Производитель — ${brand} (${place}).`]) : brand ? `Бренд — ${brand}.` : place ? `Производство — ${place}.` : "";
  const intro = `${name} — ${pick(NOUN[input.group])}. ${made}`.trim();

  // 2. Что значат характеристики
  const used = new Set<string>(["Бренд", "Страна производства"]);
  const facts: string[] = [];
  const said = new Set<string>();
  for (const s of input.specs) {
    if (isLogistics(s.name)) continue;
    const rule = RULES.find((r) => r.test.test(s.name));
    if (!rule) continue;
    used.add(s.name);
    // «Цвет» и «Цветовая гамма» — об одном: говорим один раз
    const about = /^(цвет|цветовая гамма)$/i.test(s.name) ? "цвет" : s.name;
    if (said.has(about)) continue;
    said.add(about);
    const text = rule.say(s.value, ctx);
    if (text) facts.push(text);
  }

  // 3. Остальное — списком, чтобы ничего полезного не потерять
  const skip = new Set(input.shown ?? []);
  const rest = input.specs.filter((s) => !used.has(s.name) && !skip.has(s.name) && !isLogistics(s.name) && !/^вес( нетто)?$/i.test(s.name));
  const weight = get(/^вес( нетто)?$/i);
  if (weight && !skip.has("Вес нетто") && !skip.has("Вес") && input.group !== "tips") facts.push(`Вес — ${weight}.`);

  // Писать не о чем — лучше пустое описание, чем одна дежурная фраза
  if (!facts.length && !rest.length) return "";
  const out = [intro];
  if (facts.length) out.push(facts.join(" "));
  if (rest.length) out.push(`Характеристики:\n${rest.slice(0, 30).map((s) => `— ${s.name}: ${low(s.value)}`).join("\n")}`);
  out.push(pick(CLOSE[input.group]));
  return out.join("\n\n").slice(0, 6000);
}
