/**
 * Свой «писатель» описаний товаров — без нейросети и сторонних сервисов.
 * Работает по правилам: берёт название, категорию и характеристики и собирает из них связный текст —
 * вступление, что означают характеристики для игрока, кому подойдёт, и список остальных параметров.
 * Формулировки выбираются по товару (одному товару — всегда один и тот же текст, соседним — разные),
 * поэтому описания не выглядят как под копирку. Ничего не выдумывает: о чём нет данных — молчит.
 */
import { isLogistics, type Group, type Spec } from "./fortu-parse";

/** Число из строки товара: по нему выбираем формулировки */
function seedOf(text: string) {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 16777619);
  return h >>> 0;
}

// У поставщика «зеленый», «черный» — пишем с «ё»
const YO: [RegExp, string][] = [[/зелен/g, "зелён"], [/черн(ый|ая|ое|ые|ого|ой)/g, "чёрн$1"], [/желт/g, "жёлт"], [/темно/g, "тёмно"], [/клен(?![а-я])/g, "клён"], [/слоев/g, "слоёв"], [/жестк/g, "жёстк"]];
const yo = (v: string) => YO.reduce((t, [re, to]) => t.replace(re, to), v);
const low = (v: string) => yo(v && /^[А-ЯЁ][а-яё]/.test(v) ? v[0].toLowerCase() + v.slice(1) : v);
const noDot = (v: string) => v.replace(/[.\s]+$/, "");

